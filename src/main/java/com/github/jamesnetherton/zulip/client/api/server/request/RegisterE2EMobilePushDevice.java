package com.github.jamesnetherton.zulip.client.api.server.request;

import static com.github.jamesnetherton.zulip.client.api.server.request.ServerRequestConstants.MOBILE_PUSH_REGISTER;

import com.github.jamesnetherton.zulip.client.api.core.VoidExecutableApiRequest;
import com.github.jamesnetherton.zulip.client.api.core.ZulipApiRequest;
import com.github.jamesnetherton.zulip.client.api.core.ZulipApiResponse;
import com.github.jamesnetherton.zulip.client.api.server.TokenKind;
import com.github.jamesnetherton.zulip.client.exception.ZulipClientException;
import com.github.jamesnetherton.zulip.client.http.ZulipHttpClient;

/**
 * Zulip API request builder for registering a E2E mobile push device.
 *
 * @see <a href="https://zulip.com/api/register-push-device">https://zulip.com/api/register-push-device</a>
 */
public class RegisterE2EMobilePushDevice extends ZulipApiRequest implements VoidExecutableApiRequest {
    public static final String DEVICE_ID = "device_id";
    public static final String PUSH_KEY_ID = "push_key_id";
    public static final String PUSH_KEY = "push_key";
    public static final String TOKEN_KIND = "token_kind";
    public static final String TOKEN_ID = "token_id";
    public static final String BOUNCER_PUBLIC_KEY = "bouncer_public_key";
    public static final String ENCRYPTED_PUSH_REGISTRATION = "encrypted_push_registration";

    /**
     * Constructs a {@link RegisterE2EMobilePushDevice}. An initial registration must set both the push key, via
     * {@link #withPushKey(long, String)}, and the token, via {@link #withToken(TokenKind, String, String, String)}. An
     * existing registration can rotate either one on its own.
     *
     * @param client   The Zulip HTTP client
     * @param deviceId The id of the device returned by {@code registerClientDevice()}
     */
    public RegisterE2EMobilePushDevice(ZulipHttpClient client, long deviceId) {
        super(client);
        putParam(DEVICE_ID, deviceId);
    }

    /**
     * Sets the push key used to encrypt push notifications for the device.
     *
     * @see              <a href=
     *                   "https://zulip.com/api/register-push-device#parameter-push_key">https://zulip.com/api/register-push-device#parameter-push_key</a>
     *
     * @param  pushKeyId The id of the push key, included in notifications so the device can identify which key to use
     * @param  pushKey   The push key, prefixed by a byte identifying the encryption scheme and encoded using an RFC 4648
     *                   standard base64 encoder
     * @return           This {@link RegisterE2EMobilePushDevice} instance
     */
    public RegisterE2EMobilePushDevice withPushKey(long pushKeyId, String pushKey) {
        putParam(PUSH_KEY_ID, pushKeyId);
        putParam(PUSH_KEY, pushKey);
        return this;
    }

    /**
     * Sets the FCM or APNs token for the device.
     *
     * @see                              <a href=
     *                                   "https://zulip.com/api/register-push-device#parameter-token_id">https://zulip.com/api/register-push-device#parameter-token_id</a>
     *
     * @param  tokenKind                 The {@link TokenKind} for how the token was generated
     * @param  tokenId                   The id of the token, generated by the client
     * @param  bouncerPublicKey          Bouncer public key encoded using an RFC 4648 standard base64 encoder
     * @param  encryptedPushRegistration Ciphertext generated by encrypting a PushRegistration map using the bouncer public
     *                                   key, encoded using an RFC 4648 standard base64 encoder
     * @return                           This {@link RegisterE2EMobilePushDevice} instance
     */
    public RegisterE2EMobilePushDevice withToken(TokenKind tokenKind, String tokenId, String bouncerPublicKey,
            String encryptedPushRegistration) {
        putParam(TOKEN_KIND, tokenKind.toString());
        putParam(TOKEN_ID, tokenId);
        putParam(BOUNCER_PUBLIC_KEY, bouncerPublicKey);
        putParam(ENCRYPTED_PUSH_REGISTRATION, encryptedPushRegistration);
        return this;
    }

    /**
     * Executes the Zulip API request for registering a E2E mobile push device.
     *
     * @throws ZulipClientException if the request was not successful
     */
    @Override
    public void execute() throws ZulipClientException {
        client().post(MOBILE_PUSH_REGISTER, getParams(), ZulipApiResponse.class);
    }
}
